import fs from "node:fs";
const read=p=>fs.readFileSync(new URL("../"+p,import.meta.url),"utf8");
let failed=0;
const check=(name,ok)=>{console.log((ok?"PASS ":"FAIL ")+name);if(!ok)failed++};
const access=read("lib/bos/access.ts");
const repo=read("lib/bos/onboardingRepository.ts");
const standards=read("lib/bos/core/standardRepository.ts");
const employees=read("lib/bos/core/employeeRepository.ts");
const portable=read("lib/bos/core/dataPortability.ts");
const csv=read("app/app/onboarding/data-portability/csv/route.ts");
const json=read("app/app/onboarding/data-portability/json/route.ts");
const auth=read("auth.ts");
check("verified active credentials",access.includes("status='ACTIVE' AND email_verified_at IS NOT NULL"));
check("active organization membership",access.includes("m.status='ACTIVE' AND o.status='ACTIVE'"));
check("Argon2 credential verification",auth.includes("argon2.verify(user.password_hash, password)"));
check("process tenant scope",repo.includes("WHERE p.organization_id=${orgId}"));
check("closure tenant scope",repo.includes("WHERE c.organization_id=${orgId}"));
check("process mutation tenant scope",repo.includes("organization_id=${organizationId} FOR UPDATE"));
check("actor membership validation",repo.includes("memberships WHERE organization_id=${organizationId}"));
check("standard tenant scope",standards.includes("s.organization_id=${orgId}"));
check("standard mutation tenant scope",standards.includes("s.organization_id=${organizationId}"));
check("employee tenant scope",employees.includes("organization_id=${org}"));
check("portable export tenant scope",(portable.match(/WHERE organization_id=\$\{organization\}/g)||[]).length>=8);
check("CSV requires BOS access",csv.includes("requireBOSAccess()"));
check("JSON requires BOS access",json.includes("requireBOSAccess()"));
check("CSV export allow-list",csv.includes("name in files"));
check("exports disable cache",csv.includes('"Cache-Control":"no-store"')&&json.includes('"Cache-Control":"no-store"'));
if(failed){console.error("Onboarding security contract failed: "+failed);process.exit(1)}
console.log("Onboarding security contract: PASS.");
